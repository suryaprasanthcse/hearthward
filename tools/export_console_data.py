def is_utterance(row: dict[str, Any]) -> bool:
    return row["lane"] == "wrist" and row["label"].startswith('"')


def walk_preset(name: str, scenario: dict[str, Any], sprt: dict[str, Any]) -> dict[str, Any]:
    """The observations of one run, in order, with the recorded Lambda after each (cross-device terms included)."""
    steps, observations = [], []
    a_mnats = orrery.mnats(orrery.Model.from_spec(sprt).A)
    for row in scenario["rows"]:
        if row["seq"] is None:
            continue
        utterance, claim = is_utterance(row), row["lane"] == "room" and row["label"].startswith("assess_visitor")
        if not (utterance or claim):
            continue
        observations.append(list(row["features"]) if utterance else {"claim": list(row["features"])})
        steps.append({"seq": row["seq"], "kind": "utterance" if utterance else "claim", "label": row["label"],
                      "features": list(row["features"]), "lambda_mnats": row["lambda_mnats"],
                      "delta_mnats": row["delta_mnats"], "note": row["note"]})
    crossing = next((i + 1 for i, s in enumerate(steps) if s["lambda_mnats"] >= a_mnats), None)
    return {"name": name, "summary": orrery.SCENARIOS[name]().summary, "steps": steps, "observations": observations,
            "reference_trace_mnats": orrery.reference_trace_mnats(observations, sprt), "crossing": crossing,
            "decision": scenario["decision"]["decision"] if scenario["decision"] else None,
            "cross_terms": sorted(scenario["summary"]["cross_terms"])}


def tools_view(spec: dict[str, Any]) -> list[dict[str, Any]]:
    out = []
    for tool in spec["tools"]:
        cls = tool["_meta"]["hearthward/class"]
        rules = [h["id"] for h in spec["hx"]
                 if cls in h["applies_to"] or tool["name"] in h["applies_to"] or "*" in h["applies_to"]]
        out.append({"name": tool["name"], "class": cls, "fails": "closed" if cls == "S-" else "open",
                    "description": tool["description"], "input_schema": tool["inputSchema"], "rules": rules})
    return out


def recorded(name: str) -> dict[str, Any] | None:
    path = DATA_DIR / name
    if not path.exists():
        return None
    raw = path.read_bytes()
    out = {"file": name, "file_sha256": hashlib.sha256(raw).hexdigest(), "data": json.loads(raw)}
    if "sprt_params" in out["data"]:
        # JavaScript prints 1.0 as 1, which would change params_digest: keep Python's own text for a faithful download.
        out["sprt_params_json"] = json.dumps(out["data"]["sprt_params"], sort_keys=True, separators=(",", ":"))
    return out


def action_example(ward: dict[str, Any]) -> dict[str, Any]:
    """The blocked `dismiss_alert` call of the doorstep run, as the action document HX-03 binds a passkey to."""
    sc = ward["scenarios"]["doorstep_scam"]
    proof = next(r for r in sc["rows"] if r["event"] == "PROOF_REQ")
    nonce = base64.urlsafe_b64encode(hashlib.sha256(b"hearthward console demo nonce (synthetic)").digest()[:16])
    return {"seq": proof["seq"], "rules": proof["hx_rules"],
            "document": {"tool": "dismiss_alert",
                         "args": {"episode_id": sc["decision"]["episode"], "reason": "false_alarm"},
                         "household": ward["household"], "episode_version": 3,
                         "nonce": nonce.rstrip(b"=").decode("ascii"), "exp": ward["epoch_ms"] + 360_000}}


