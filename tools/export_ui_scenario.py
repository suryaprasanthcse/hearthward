#!/usr/bin/env python3
"""Export one orrery run to `web/src/radar_data.js`, the synthetic replay the Bitemporal Causal Radar page plays.

    python tools/export_ui_scenario.py            # write the file
    python tools/export_ui_scenario.py --check    # exit 1 if the file on disk is stale

Everything in the file comes from `tools/orrery.py` (scenario `doorstep_scam`, seed 7) and is synthetic: the ledger
envelopes with their real hash chain, the evidence Lambda after each event, the temporal parameters, and a decision
record signed with a throwaway, public, *synthetic* P-256 key (not KMS) so the page can verify a signature in the
browser. The output is byte-deterministic.
"""

from __future__ import annotations

import argparse
import base64
import hashlib
import json
import sys
from pathlib import Path
from typing import Any

sys.path.insert(0, str(Path(__file__).resolve().parent))
import orrery
import verify_attestation as va

OUT = orrery.ROOT / "web" / "src" / "radar_data.js"
SCENARIO, SEED = "doorstep_scam", 7
SYNTHETIC_KEY = int.from_bytes(hashlib.sha256(b"hearthward radar demo key (synthetic, public)").digest(), "big") % va.N
HEADER = """// GENERATED by tools/export_ui_scenario.py from tools/orrery.py. Do not edit; run the tool again instead.
// SYNTHETIC DATA: every event, hash and number below was produced by the reference simulator, and the signature is
// made with a throwaway public key, not KMS.
"""


def build() -> dict[str, Any]:
    spec = orrery.load_spec()
    problems, runs = orrery.selftest(spec)
    assert problems == [], problems
    run = runs[SCENARIO]
    summary = run.summary
    envelopes = run.envelopes
    by_seq = {row.seq: row for row in run.rows if row.seq is not None}
    steps = [{"seq": e["seq"], "lambda_mnats": by_seq[e["seq"]].lambda_mnats,
              "delta_mnats": by_seq[e["seq"]].delta_mnats, "features": by_seq[e["seq"]].features,
              "label": by_seq[e["seq"]].label, "note": by_seq[e["seq"]].note} for e in envelopes]
    intervene = next(row for row in run.rows if row.event == "INTERVENE")
    at_seq = max(e["seq"] for e in envelopes if by_seq[e["seq"]].at <= intervene.at)
    head_at = next(e["head"] for e in envelopes if e["seq"] == at_seq)
    sprt_text = json.dumps(spec["sprt"], sort_keys=True, separators=(",", ":")).encode("utf-8")
    crockford = "0123456789ABCDEFGHJKMNPQRSTVWXYZ"
    episode_bits = int.from_bytes(hashlib.sha256(b"hearthward radar demo episode (synthetic)").digest()[:16], "big")
    episode = "ep_" + "".join(crockford[(episode_bits >> shift) & 31] for shift in range(125, -1, -5))
    record = {
        "episode": episode, "decision": summary["decision"], "at_seq": at_seq, "belief_seq": at_seq,
        "ledger_head": head_at, "lambda_mnats": intervene.lambda_mnats,
        "reasons": sorted({f for st in steps if st["seq"] <= at_seq for f in st["features"]}),
        "thresholds_mnats": {"a": 4554, "b": -2986},
        "params_digest": "sha256:" + hashlib.sha256(sprt_text).hexdigest(),
        "extractor_model_ids": ["synthetic-orrery-labels"], "cross_terms": sorted(summary["cross_terms"])}
    data = va.jcs(record)
    r, s = va.ecdsa_sign(SYNTHETIC_KEY, data)
    pub = va.mul(SYNTHETIC_KEY, va.G)
    attestation = {
        "v": 1, "public_key_b64": base64.b64encode(va.encode_public_key(pub)).decode("ascii"),
        "decision": {"bytes_b64": base64.b64encode(data).decode("ascii"),
                     "sig_b64": base64.b64encode(va.encode_signature(r, s)).decode("ascii"),
                     "key_id": "synthetic-demo-key"},
        "decision_digest": va.tagged(b"hw-decision-v1", data)}
    return {
        "scenario": SCENARIO, "seed": SEED, "synthetic": True,
        "thresholds_mnats": {"a": 4554, "b": -2986},
        "temporal": {k: spec["temporal"][k] for k in ("lateness_ms", "visit_gap_ms")},
        "household": envelopes[0]["household"],
        "envelopes": [{k: e[k] for k in ("seq", "source", "kind", "valid", "src_time", "received_at", "prev", "head",
                                         "household", "v", "source_event_id", "raw_digest", "payload_digest", "auth",
                                         "sent_time")} for e in envelopes],
        "steps": steps,
        "intervene_at_seq": at_seq,
        "proof_required_at_seq": next((row.seq for row in run.rows if row.event == "PROOF_REQ"), None),
        "attestation": attestation,
    }


def render(data: dict[str, Any]) -> bytes:
    body = json.dumps(data, sort_keys=True, indent=2, ensure_ascii=True)
    return (HEADER + f"export const SCENARIO = {body};\n").encode("ascii")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Export an orrery run for the radar page.")
    parser.add_argument("--check", action="store_true", help="compare with the file on disk instead of writing")
    args = parser.parse_args(argv)
    data = render(build())
    if args.check:
        stale = not OUT.exists() or OUT.read_bytes() != data
        print(f"stale: {OUT}" if stale else "up to date")
        return 1 if stale else 0
    OUT.write_bytes(data)
    print(OUT)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
