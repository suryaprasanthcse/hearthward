def test_the_browser_action_hash_equals_the_brokers() -> None:
    action = export.build()["action"]["document"]
    expected = action_hash(action["tool"], action["args"], action["household"], action["episode_version"],
                           action["nonce"], action["exp"]).hex()
    script = ("import { CONSOLE } from './console/data/console_data.js';"
              "import { actionDocument, actionHash } from './console/claims/asymmetry.js';"
              "const { doc } = actionDocument(CONSOLE, { tool: 'dismiss_alert', args: {}, nonce: null, exp: null });"
              "process.stdout.write((await actionHash(doc)).hex);")
