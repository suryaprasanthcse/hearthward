"""Gate G6 (web): the Bitemporal Causal Radar page, its generated scenario data and its static-hosting hygiene."""

from __future__ import annotations

import re
from pathlib import Path

import export_ui_scenario
import pytest

pytestmark = pytest.mark.gate_g6

ROOT = Path(__file__).resolve().parents[2]
WEB = ROOT / "web"
INDEX = (WEB / "radar/index.html").read_text(encoding="utf-8")
SOURCES = {p.name: p.read_text(encoding="utf-8") for p in (WEB / "src").glob("*.js")}
RADAR_FILES = ("radar.js", "radar_logic.js", "fluid.js", "radar_data.js")


def test_the_generated_scenario_matches_a_fresh_export_byte_for_byte() -> None:
    assert export_ui_scenario.OUT.read_bytes() == export_ui_scenario.render(export_ui_scenario.build())


def test_the_generated_file_is_ascii_lf_and_says_it_is_synthetic() -> None:
    data = (WEB / "src/radar_data.js").read_bytes()
    assert data.isascii() and b"\r" not in data and data.startswith(b"// GENERATED by tools/export_ui_scenario.py")
    assert b"SYNTHETIC DATA" in data[:400] and b"export const SCENARIO" in data


def test_the_export_is_deterministic() -> None:
    assert export_ui_scenario.render(export_ui_scenario.build()) == export_ui_scenario.render(export_ui_scenario.build())


def test_the_page_has_every_panel_the_brief_names() -> None:
    for needle in ("WALD SPRT EVIDENCE ACCUMULATOR", "REAL-TIME SPRT TREND", "BITEMPORAL ORBITS", "INTERVENE ESCALATION LADDER",
                   "AUDIT LEDGER", "BELIEF SEQUENCE TIME-TRAVEL SCRUBBER", "fluid-toggle", 'id="fluid"', 'id="pyramid"',
                   "L3", "L2", "L1", "VOICE", "PRIORITY", "ALERT", 'href="../verify.html"', 'href="../approve.html"'):
        assert needle in INDEX, needle
    for tier in ("MDCCLXXVI", "ANNUIT COEPTIS", "TRUST CAUSALIS", "ORDO CAUSALIS"):
        assert tier in SOURCES["radar.js"], tier
    for lane in ("DOOR", "ROOM", "WRIST", "W_ring", "W_bee", "W_alexa", "vf_lo", "vf_hi"):
        assert lane in SOURCES["radar.js"], lane


def test_the_page_is_labelled_synthetic_and_claims_no_unmeasured_numbers() -> None:
    assert "SYNTHETIC DEMO DATA" in INDEX
    assert "GATE G7 COMPLETE" not in INDEX and "GATE G7 COMPLETE" not in SOURCES["radar.js"]
    combined = INDEX + "".join(SOURCES[f] for f in RADAR_FILES if f != "radar_data.js")
    assert "60 fps" not in combined.lower()  # the toggle shows the measured rate, never a promised one
    assert "performance.now()" in SOURCES["radar.js"] and "FPS" in SOURCES["radar.js"]


def test_the_page_needs_no_network_beyond_its_own_files() -> None:
    assert not re.search(r"<script(?![^>]*\bsrc=)[^>]*>", INDEX) and "style=" not in INDEX and "onclick" not in INDEX
    assert re.findall(r'<script type="module" src="(\.\./src/[a-z_]+\.js)"', INDEX) == ["../src/radar.js"]
    for name in RADAR_FILES:
        text = SOURCES[name]
        urls = [u for u in re.findall(r"https?://[^\s\"'`)]+", text) if u != "http://www.w3.org/2000/svg"]
        assert urls == [] or name == "radar_data.js", (name, urls)
        assert "fetch(" not in text and "XMLHttpRequest" not in text and "WebSocket" not in text and "eval(" not in text, name
        assert ".innerHTML" not in text and "document.write" not in text, name
    for ref in re.findall(r'(?:src|href)="([^"]+)"', INDEX):
        assert (WEB / "radar" / ref).resolve().is_file(), ref


def test_every_import_in_the_radar_modules_resolves_to_a_file() -> None:
    for name in ("radar.js", "radar_logic.js", "fluid.js", "attest.js"):
        for target in re.findall(r'from "\./([a-z_]+\.js)"', SOURCES[name]):
            assert (WEB / "src" / target).is_file(), (name, target)


def test_no_style_attributes_are_set_from_script() -> None:
    """The page's CSP allows only the stylesheet file, so script must not write `style` attributes."""
    for name in RADAR_FILES:
        assert not re.search(r"""setAttribute\(\s*["']style["']""", SOURCES[name]) and "style:" not in SOURCES[name], name


def test_the_fluid_has_the_navier_stokes_passes_and_degrades_without_webgl2() -> None:
    fluid = SOURCES["fluid.js"]
    for stage in ("advection", "divergence", "pressure", "vorticity", "gradient", "curl", "splat"):
        assert f"{stage}:" in fluid, stage
    assert "webgl2" in fluid and "return null" in fluid
    assert "UNAVAILABLE" in SOURCES["radar.js"] and "prefers-reduced-motion" in SOURCES["radar.js"]


def test_the_page_uses_no_package_manager_dependencies() -> None:
    package = (WEB / "package.json").read_text(encoding="utf-8")
    assert '"dependencies"' not in package and '"devDependencies"' not in package
