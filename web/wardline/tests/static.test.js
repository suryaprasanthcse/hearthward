// node --test web/wardline/tests. Static checks: CSP, no network, honesty strings, generated data, colour tokens.
import assert from "node:assert/strict";
import { readFileSync, readdirSync } from "node:fs";
import { test } from "node:test";

const dir = new URL("../", import.meta.url);
const read = (name) => readFileSync(new URL(name, dir), "utf8");
const jsFiles = readdirSync(dir).filter((f) => f.endsWith(".js"));
const textFiles = [...readdirSync(dir).filter((f) => /\.(js|css|html|md|py)$/.test(f))];
const html = read("index.html");
const css = read("wardline.css");

test("index.html carries the CSP and exactly one module script, with nothing inline", () => {
  assert.match(html, /<meta http-equiv="Content-Security-Policy"\s+content="default-src 'none'; script-src 'self'; style-src 'self'; img-src 'self' data:; base-uri 'none'; form-action 'none'">/);
  const scripts = [...html.matchAll(/<script\b[^>]*>/g)].map((m) => m[0]);
  assert.deepEqual(scripts, ['<script type="module" src="main.js">']);
  assert.equal([...html.matchAll(/<script\b[^>]*>([\s\S]*?)<\/script>/g)].every((m) => m[1].trim() === ""), true);
  assert.equal(/<style\b/i.test(html), false, "inline <style>");
  assert.equal(/\sstyle\s*=/i.test(html), false, "style= attribute");
  assert.equal(/\son[a-z]+\s*=/i.test(html), false, "on*= handler");
  assert.equal([...html.matchAll(/<link\b[^>]*rel="stylesheet"[^>]*>/g)].length, 1);
  assert.match(html, /<noscript>/);
});

test("every import is relative and nothing touches the network", () => {
  for (const file of jsFiles) {
    const src = read(file);
    for (const m of src.matchAll(/(?:^|\n)\s*(?:import|export)\b[^;]*?\bfrom\s+["']([^"']+)["']/g)) {
      assert.ok(m[1].startsWith("./"), `${file}: import ${m[1]}`);
    }
    for (const m of src.matchAll(/\bimport\s*\(\s*["']([^"']+)["']/g)) assert.ok(m[1].startsWith("./"), `${file}: dynamic import`);
    const urls = [...src.matchAll(/https?:\/\/[^\s"'`)]+/g)].map((m) => m[0]).filter((u) => u !== "http://www.w3.org/2000/svg");
    assert.deepEqual(urls, [], `${file}: URLs`);
    for (const banned of ["fetch(", "XMLHttpRequest", "WebSocket", "eval(", "importScripts", "sendBeacon"]) {
      if (file === "static.test.js") continue;
      assert.equal(src.includes(banned), false, `${file}: ${banned}`);
    }
  }
  assert.equal(/https?:\/\//.test(css), false);
  assert.equal(/@import|url\(\s*["']?https?:/.test(css), false);
});

test("no frame-rate claim appears anywhere (D-5), and the synthetic data is disclosed", () => {
  const banned = new RegExp(`6${"0"}\\s*fps`, "i");
  for (const file of textFiles) assert.equal(banned.test(read(file)), false, file);
  assert.ok(html.includes("SYNTHETIC DEMO DATA"));
  assert.ok(read("main.js").includes("mean of the last 60 requestAnimationFrame intervals"));
});

test("data.js is generated ASCII with LF only and carries no private key material", () => {
  const data = readFileSync(new URL("data.js", dir));
  assert.ok(data.every((b) => b < 0x80), "ASCII");
  assert.equal(data.includes(0x0d), false, "CR");
  const text = data.toString("ascii");
  assert.ok(text.startsWith("// GENERATED by web/wardline/export_data.py"));
  assert.equal(/PRIVATE|BEGIN/.test(text), false);
  assert.equal(readFileSync(new URL(".gitattributes", dir), "utf8").trim(), "data.js -text");
});

test("every GLSL colour equals its CSS token, and the wave constants agree", () => {
  const gl = read("ward.gl.js");
  const tokens = { BG: "--bg-0", INK: "--ink-1", SCAM: "--toward-scam", HOT: "--intervene", SAFE: "--toward-benign", VER: "--verified" };
  for (const [name, token] of Object.entries(tokens)) {
    const m = new RegExp(`const vec3 ${name}\\s*=\\s*vec3\\(([^)]*)\\)`).exec(gl);
    assert.ok(m, name);
    const glsl = m[1].split(",").map(Number);
    const hex = new RegExp(`${token}:\\s*#([0-9A-Fa-f]{6})`).exec(css)[1];
    const rgb = [0, 2, 4].map((i) => parseInt(hex.slice(i, i + 2), 16) / 255);
    glsl.forEach((v, i) => assert.ok(Math.abs(v - rgb[i]) < 0.0006, `${name}[${i}] ${v} vs ${rgb[i].toFixed(4)}`));
  }
  const model = read("model.js");
  for (const [needle, label] of [["/ 60.0", "60"], ["/ 0.35", "0.35"], ["18.849556", "3 Hz"]]) assert.ok(gl.includes(needle), `ward.gl.js ${label}`);
  for (const [needle, label] of [["/ 60;", "60"], ["/ 0.35", "0.35"], ["18.849556", "3 Hz"]]) assert.ok(model.includes(needle), `model.js ${label}`);
  assert.match(model, /sigmaPx: 60, decayS: 0.35, hz: 3/);
  assert.ok(Math.abs(2 * Math.PI * 3 - 18.849556) < 1e-6);
});

test("the stage is 1920 x 1080 and every act has an SVG group and a HUD section", () => {
  assert.match(html, /viewBox="0 0 1920 1080"/);
  for (const id of ["glow", "ink", "act1", "act2", "act3", "lattice", "hud1", "hud2", "hud3", "card", "transcript", "sentence", "debug"]) {
    assert.ok(html.includes(`id="${id}"`), id);
  }
  assert.match(html, /id="sentence" aria-live="polite"/);
  assert.match(html, /<canvas id="glow" aria-hidden="true">/);
  assert.match(html, /<svg id="ink"[^>]*aria-hidden="true"/);
  assert.match(css, /#stage \{[^}]*width: 1920px; height: 1080px;/);
});
