#!/usr/bin/env python3
"""Export three orrery runs to `web/wardline/data.js`, the synthetic replay the Wardline instrument plays.

    uv run python web/wardline/export_data.py            # write the file
    uv run python web/wardline/export_data.py --check    # exit 1 if the file on disk is stale

Everything in the file comes from `tools/orrery.py` (seed 7; scenarios doorstep_scam, late_and_lossy and
verified_plumber) and is synthetic. The doorstep_scam decision record is signed with the throwaway public key of
`tools/export_ui_scenario.py` (key_id synthetic-demo-key), not KMS. The output is byte-deterministic.
"""

from __future__ import annotations

import argparse
import json
import math
import re
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "tools"))
import orrery
import export_ui_scenario as ui

OUT = Path(__file__).resolve().parent / "data.js"
SEED = 7
SCENARIOS = ("doorstep_scam", "late_and_lossy", "verified_plumber")
SAFE_INT = 2**53 - 1
HX_IDS = re.compile(r"PROOF_REQUIRED \[([^\]]*)\]")
HEADER = """// GENERATED by web/wardline/export_data.py from tools/orrery.py (seed 7). Do not edit; run the exporter again.
// SYNTHETIC DATA: every event, hash and number below comes from the reference simulator. The decision signature
// uses a throwaway public synthetic key (key_id synthetic-demo-key), not KMS.
"""


def posterior_ppm(log_alpha: list[float] | None) -> list[int] | None:
    """P(stage | observations, H1) as integers summing to exactly 1,000,000 (largest remainder, ties to the lower stage)."""
    if log_alpha is None:
        return None
    top = max(log_alpha)
    weights = [0.0 if a == -math.inf else math.exp(a - top) for a in log_alpha]
    total = sum(weights)
    exact = [w / total * 1_000_000 for w in weights]
    floors = [math.floor(x) for x in exact]
    order = sorted(range(len(exact)), key=lambda i: (-(exact[i] - floors[i]), i))
    for i in order[: 1_000_000 - sum(floors)]:
        floors[i] += 1
    return floors


def strip_inf(value: Any) -> Any:
    """INF (the 'still open' sentinel) becomes null, and no integer may exceed the HW-JCS safe range."""
    if isinstance(value, bool) or value is None or isinstance(value, str):
        return value
    if isinstance(value, int):
        if value == orrery.INF:
            return None
        assert abs(value) <= SAFE_INT, value
        return value
    if isinstance(value, list):
        return [strip_inf(v) for v in value]
    if isinstance(value, dict):
        return {k: strip_inf(v) for k, v in value.items()}
    raise TypeError(f"unexpected {type(value).__name__}")


def run_scenario(spec: dict[str, Any], name: str) -> dict[str, Any]:
    o = orrery.Orrery(spec, orrery.SCENARIOS[name](), SEED)
    rows: list[dict[str, Any]] = []
    plain: list[orrery.Row] = []
    for row in o.run():
        plain.append(row)
        marks = (m := HX_IDS.search(row.note)) if row.event == "PROOF_REQ" else None
        rows.append({
            **row.as_dict(),
            "posterior_ppm": posterior_ppm(o.acc.log_alpha),
            "watermarks": {lane: (None if (w := o.watermark(lane)) == orrery.INF else w) for lane in orrery.LANES},
            "flushed": o.flushed,
            "hx_rules": [x.strip() for x in marks.group(1).split(",")] if marks else [],
        })
    versions = [{"fid": v.fid, "n": v.n, "vf_lo": v.vf_lo, "vf_hi": v.vf_hi, "vt": v.vt, "ts": v.ts, "te": v.te,
                 "data": v.data} for vs in o.store.versions.values() for v in vs]
    return strip_inf({"summary": o.summary(plain), "rows": rows, "envelopes": o.ledger, "versions": versions,
                      "decision": o.decision, "decision_digest": o.decision_digest})


def build() -> dict[str, Any]:
    spec = orrery.load_spec()
    signed = ui.build()
    scenarios = {name: run_scenario(spec, name) for name in SCENARIOS}
    heads = [e["head"] for e in scenarios["doorstep_scam"]["envelopes"]]
    assert heads == [e["head"] for e in signed["envelopes"]], "doorstep_scam ledger disagrees with the signed export"
    model = orrery.Model.from_spec(spec["sprt"])
    temporal = spec["temporal"]
    data = {
        "synthetic": True, "seed": SEED, "epoch_ms": orrery.EPOCH_MS, "household": orrery.HOUSEHOLD,
        "sprt": {"a_mnats": orrery.mnats(model.A), "b_mnats": orrery.mnats(model.B),
                 "stages": list(model.stages), "features": list(model.features),
                 "cross_device_llr_mnats": {k: orrery.mnats(v) for k, v in model.cross.items()}},
        "temporal": {"lateness_ms": temporal["lateness_ms"], "visit_gap_ms": temporal["visit_gap_ms"],
                     "epsilon_ring_ms": temporal["epsilon_ring_ms"], "delta_ms": temporal["delta_ms"]},
        "hx": [{"id": h["id"], "title": h["title"]} for h in spec["hx"]],
        "scenarios": scenarios,
        "signed": {"scenario": ui.SCENARIO, "intervene_at_seq": signed["intervene_at_seq"],
                   "proof_required_at_seq": signed["proof_required_at_seq"], "attestation": signed["attestation"]},
    }
    orrery.canonical(data)  # raises on floats and on keys outside ^[a-z0-9_]+$
    return data


def render(data: dict[str, Any]) -> bytes:
    body = json.dumps(data, sort_keys=True, indent=1, ensure_ascii=True)
    return (HEADER + f"export const WARD = {body};\n").encode("ascii")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Export orrery runs for the Wardline instrument.")
    parser.add_argument("--check", action="store_true", help="compare with the file on disk instead of writing")
    args = parser.parse_args(argv)
    data = render(build())
    if args.check:
        stale = not OUT.exists() or OUT.read_bytes() != data
        print(f"stale: {OUT}" if stale else "up to date")
        return 1 if stale else 0
    OUT.write_bytes(data)
    print(OUT)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
